import pandas as pd
import numpy as np

transactions = pd.read_csv("transactions.csv")
products = pd.read_csv("products.csv")
stores = pd.read_csv("stores.csv")
inventory = pd.read_csv("inventory.csv")
external = pd.read_csv("external_factors.csv")

