transactions = transactions.drop_duplicates(
    subset="transaction_id"
)

transactions.loc[
    transactions["quantity"] < 0, "quantity"
] = np.nan

products["category"] = (
    products["category"]
    .str.strip()
    .str.lower()
)

products["category"] = products["category"].replace({
    "beverage": "beverages",
    "personal care": "personal care",
    "dairy": "dairy",
    "snacks": "snacks",
    "household": "household"
})

print(products["category"].unique())

print(products.isnull().sum())

print(products["product_id"].duplicated().sum())

print("Transactions:")
print(transactions.isnull().sum())
print("Duplicates:", transactions.duplicated().sum())

print("\nInventory:")
print(inventory.isnull().sum())
print("Duplicates:", inventory.duplicated().sum())

print("\nStores:")
print(stores.isnull().sum())
print("Duplicates:", stores.duplicated().sum())

print("\nExternal:")
print(external.isnull().sum())
print("Duplicates:", external.duplicated().sum())

print(transactions[transactions["quantity"] < 0])

transactions = transactions[transactions["quantity"] >= 0]

daily_sales = (
    transactions
    .groupby(["date", "store_id", "product_id"])
    .agg(
        demand=("quantity", "sum"),
        selling_price=("selling_price", "mean"),
        discount_pct=("discount_pct", "mean"),
        promotion_flag=("promotion_flag", "max")
    )
    .reset_index()
)

print(daily_sales.head())
print(daily_sales.shape)

daily_sales["date"] = pd.to_datetime(daily_sales["date"])
inventory["date"] = pd.to_datetime(inventory["date"])
external["date"] = pd.to_datetime(external["date"])

master = daily_sales.merge(
    inventory,
    on=["date", "store_id", "product_id"],
    how="left"
)

print(master.shape)
print(master.head())

master = master.merge(
    products,
    on="product_id",
    how="left"
)

print(master.shape)

master = master.merge(
    stores,
    on="store_id",
    how="left"
)

master = master.merge(
    external,
    on=["date", "city"],
    how="left"
)

print(master.shape)
print(master.columns.tolist())
print(master.head())

print(master.isnull().sum())

master.to_csv(
    "master_dataset.csv",
    index=False
)

import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

master = pd.read_csv("master_dataset.csv")
master["date"] = pd.to_datetime(master["date"])

print(master.shape)
master.head()

master["revenue"] = master["demand"] * master["selling_price"]

category_revenue = (
    master.groupby("category")["revenue"]
    .sum()
    .sort_values(ascending=False)
)

print(category_revenue)

category_revenue.plot(kind="bar", figsize=(8,5))

plt.title("Revenue by Product Category")
plt.xlabel("Category")
plt.ylabel("Revenue")
plt.xticks(rotation=45)
plt.show()

store_sales = (
    master.groupby(["date", "store_id"])["revenue"]
    .sum()
    .reset_index()
)

plt.figure(figsize=(10,5))

sns.lineplot(
    data=store_sales,
    x="date",
    y="revenue",
    hue="store_id"
)

plt.title("Daily Revenue by Store")
plt.xlabel("Date")
plt.ylabel("Revenue")
plt.show()

promotion_sales = (
    master.groupby("promotion_flag")["demand"]
    .mean()
)

print(promotion_sales)

promotion_sales.plot(
    kind="bar",
    figsize=(6,4)
)

plt.title("Average Demand: Promotion vs No Promotion")
plt.xlabel("Promotion")
plt.ylabel("Average Demand")
plt.xticks([0,1], ["No Promotion", "Promotion"], rotation=0)
plt.show()

weekend_demand = (
    master.groupby("weekend")["demand"]
    .mean()
)

print(weekend_demand)

weekend_demand.plot(
    kind="bar",
    figsize=(6,4)
)

plt.title("Weekend vs Weekday Demand")
plt.xlabel("Day Type")
plt.ylabel("Average Demand")
plt.xticks([0,1], ["Weekday", "Weekend"], rotation=0)
plt.show()

product_stats = (
    master.groupby("product_id")["demand"]
    .agg(["mean", "std"])
)

product_stats["CV"] = (
    product_stats["std"] /
    product_stats["mean"]
)

print(
    product_stats.sort_values(
        "CV",
        ascending=False
    ).head(10)
)

master["stockout_flag"] = (
    (master["closing"] == 0) &
    (master["demand"] > 0)
).astype(int)

stockouts = (
    master.groupby("store_id")["stockout_flag"]
    .sum()
    .sort_values(ascending=False)
)

print(stockouts)

heatmap_data = pd.pivot_table(
    master,
    values="stockout_flag",
    index="store_id",
    columns="category",
    aggfunc="sum",
    fill_value=0
)

plt.figure(figsize=(10,5))

sns.heatmap(
    heatmap_data,
    annot=True,
    fmt="g"
)

plt.title("Stock-out Heatmap by Store and Category")
plt.xlabel("Category")
plt.ylabel("Store")
plt.show()

master.to_csv(
    "master_dataset.csv",
    index=False
)

