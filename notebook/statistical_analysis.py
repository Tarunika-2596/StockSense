import pandas as pd
from scipy.stats import ttest_ind, f_oneway, chi2_contingency
master = pd.read_csv("/master_dataset.csv")

promo = master[master["promotion_flag"] == 1]["demand"]
no_promo = master[master["promotion_flag"] == 0]["demand"]

t_stat, p_value = ttest_ind(
    promo,
    no_promo,
    equal_var=False
)

print("T-statistic:", t_stat)
print("P-value:", p_value)

if p_value < 0.05:
    print("Significant difference: promotion affects demand.")
else:
    print("No significant difference found.")

print("Promotion mean:", promo.mean())
print("No promotion mean:", no_promo.mean())

groups = [
    group["demand"].dropna()
    for name, group in master.groupby("store_type")
]

f_stat, p_value = f_oneway(*groups)

print("F-statistic:", f_stat)
print("P-value:", p_value)

if p_value < 0.05:
    print("Significant difference in demand across store types.")
else:
    print("No significant difference in demand across store types.")

print(
    master.groupby("store_type")["demand"].mean()
)

master["stockout_flag"] = (
    (master["closing"] == 0) &
    (master["demand"] > 0)
).astype(int)

table = pd.crosstab(
    master["promotion_flag"],
    master["stockout_flag"]
)

print(table)

chi2, p_value, dof, expected = chi2_contingency(table)

print("Chi-square:", chi2)
print("P-value:", p_value)

if p_value < 0.05:
    print("Stock-out frequency is significantly associated with promotion.")
else:
    print("No significant association found.")

